import { describe, expect, it } from "vitest";
import {
  cleanTrackForLookup,
  normalizeDate,
  parseReleaseDateFromDescription,
} from "../src/lib/releaseDate";
import { resolveReleaseDate } from "../src/jobs/persistUserData";
import { pickReleaseDate } from "../src/services/MusicBrainzService";
import { video } from "./youtubeFakes";

const TOPIC_DESCRIPTION = `Provided to YouTube by Asylum

Hotel California (2013 Remaster) · Eagles

Hotel California

℗ 2013 Elektra/Asylum Records

Released on: 2013-02-12

Auto-generated by YouTube.`;

describe("parseReleaseDateFromDescription", () => {
  it("prefers the 'Released on' date", () => {
    expect(parseReleaseDateFromDescription(TOPIC_DESCRIPTION)).toBe("2013-02-12");
  });

  it("copes with Windows line endings and non-breaking spaces", () => {
    const messy = TOPIC_DESCRIPTION.replace(/\n/g, "\r\n")
      .replace("Released on: ", "Released on:\u00a0")
      .replace("℗ 2013", "℗\u00a02013");
    expect(parseReleaseDateFromDescription(messy)).toBe("2013-02-12");
    expect(
      parseReleaseDateFromDescription("Provided to YouTube by X\r\n\r\n℗\u00a01979 Label"),
    ).toBe("1979");
  });

  it("falls back to the ℗ year", () => {
    expect(parseReleaseDateFromDescription("℗ 1983 RCA Records")).toBe("1983");
    expect(parseReleaseDateFromDescription("(P) 1971 Atlantic")).toBe("1971");
  });

  it("ignores missing or implausible dates", () => {
    expect(parseReleaseDateFromDescription("Subscribe for more!")).toBeNull();
    expect(parseReleaseDateFromDescription(undefined)).toBeNull();
    expect(parseReleaseDateFromDescription("Released on: 0001-01-01")).toBeNull();
    expect(parseReleaseDateFromDescription("℗ 3021")).toBeNull();
  });

  it("normalizes partial MusicBrainz dates", () => {
    expect(normalizeDate("1977")).toBe("1977");
    expect(normalizeDate("1977-02")).toBe("1977-02");
    expect(normalizeDate("")).toBeNull();
  });
});

describe("cleanTrackForLookup", () => {
  it.each([
    ["Eagles - Hotel California (Official Video)", "EaglesVEVO", "Eagles", "Hotel California"],
    ["Hotel California (2013 Remaster)", "Eagles - Topic", "Eagles", "Hotel California"],
    ["Bad Guy [Lyrics]", "Billie Eilish", "Billie Eilish", "Bad Guy"],
    ["Uptown Funk ft. Bruno Mars", "Mark Ronson", "Mark Ronson", "Uptown Funk"],
    [
      "Daft Punk - Get Lucky (Official Audio) ft. Pharrell Williams",
      "Daft Punk",
      "Daft Punk",
      "Get Lucky",
    ],
    [
      "Sweet Dreams (Are Made of This) (Remastered)",
      "Eurythmics - Topic",
      "Eurythmics",
      "Sweet Dreams (Are Made of This)",
    ],
  ])("%s / %s", (title, channel, artist, cleanTitle) => {
    expect(cleanTrackForLookup(title, channel)).toEqual({ artist, title: cleanTitle });
  });
});

describe("resolveReleaseDate", () => {
  it("uses the description, then the cache, then the upload date", () => {
    const topic = { ...video("a"), description: "Released on: 1976-12-08" };
    expect(resolveReleaseDate(topic)).toEqual({
      releaseDate: "1976-12-08",
      releaseDateSource: "youtube",
    });
    expect(resolveReleaseDate(video("b"), "1969")).toEqual({
      releaseDate: "1969",
      releaseDateSource: "musicbrainz",
    });
    expect(resolveReleaseDate(video("c"))).toEqual({
      releaseDate: "2015-06-01",
      releaseDateSource: "upload",
    });
  });

  it("lets an earlier looked-up date beat a remaster's description date", () => {
    const remaster = { ...video("d"), description: TOPIC_DESCRIPTION };
    expect(resolveReleaseDate(remaster, "1976-12-08").releaseDateSource).toBe(
      "musicbrainz",
    );
    expect(resolveReleaseDate(remaster, "2020").releaseDateSource).toBe("youtube");
  });
});

describe("pickReleaseDate", () => {
  const rec = (score: number, title: string, artist: string, date?: string) => ({
    id: `${title}-${date}`,
    score,
    title,
    "first-release-date": date,
    "artist-credit": [{ name: artist, artist: { name: artist } }],
  });

  it("takes the earliest confident match", () => {
    expect(
      pickReleaseDate(
        [
          rec(100, "Hotel California", "Eagles", "2013-02-12"),
          rec(98, "Hotel California", "Eagles", "1976-12-08"),
          rec(70, "Hotel California", "Eagles", "1950"),
        ],
        "Eagles",
        "Hotel California",
      ),
    ).toBe("1976-12-08");
  });

  it("rejects other artists, unrelated titles and dateless results", () => {
    expect(
      pickReleaseDate(
        [
          rec(100, "Hotel California", "Gipsy Kings", "1990"),
          rec(100, "Take It Easy", "Eagles", "1972"),
          rec(100, "Hotel California", "The Eagles"),
        ],
        "Eagles",
        "Hotel California",
      ),
    ).toBeNull();
  });

  it("matches case/accent/'the' differences", () => {
    expect(
      pickReleaseDate([rec(95, "Jóga", "Björk", "1997")], "bjork", "Joga"),
    ).toBe("1997");
  });
});
